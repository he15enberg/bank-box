  /// Flat map: Sender Code -> Bank Name (for quick SMS parsing)
  static Map<String, String> get senderCodeToBankMap {
    final Map<String, String> flatMap = {};
    bankTransactionSmsCodes.forEach((bankName, codes) {
      for (final code in codes) {
        flatMap[code] = bankName;
      }
    });
    return flatMap;
  }

  /// Get all bank names
  static List<String> get allBankNames =>
      bankTransactionSmsCodes.keys.toList()..sort();

  /// Get all codes for a specific bank
  static List<String> getCodesForBank(String bankName) {
    return bankTransactionSmsCodes[bankName] ?? [];
  }

  /// Get all sender codes (flat list)
  static List<String> get allCodes {
    final List<String> codes = [];
    bankTransactionSmsCodes.forEach((_, bankCodes) {
      codes.addAll(bankCodes);
    });
    return codes;
  }

  /// Check if sender is from any known bank
  static bool isBankSender(String sender) {
    final upperSender = sender.toUpperCase();
    return senderCodeToBankMap.keys.any((code) => upperSender.contains(code));
  }

  /// Find the bank code from sender string
  static String? findBankCode(String sender) {
    final upperSender = sender.toUpperCase();
    for (final code in senderCodeToBankMap.keys) {
      if (upperSender.contains(code)) {
        return code;
      }
    }
    return null;
  }

  /// Get bank name from sender code
  static String getBankName(String code) {
    return senderCodeToBankMap[code] ?? 'Unknown Bank';
  }

  /// Get bank name directly (for display)
  static String getBankNameDirect(String bankName) {
    return bankTransactionSmsCodes.containsKey(bankName)
        ? bankName
        : 'Unknown Bank';
  }

  /// Find bank name from sender string
  static String? findBankName(String sender) {
    final code = findBankCode(sender);
    if (code != null) {
      return getBankName(code);
    }
    return null;
  }

  /// Get total number of banks
  static int get totalBanks => bankTransactionSmsCodes.length;

  /// Get total number of sender codes
  static int get totalCodes => allCodes.length;
